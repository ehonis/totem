const t = (key: string, values: Record<string, string | number> = {}) => {
  const name = key.replace("quota_management.", "");
  const plural =
    typeof values.count === "number"
      ? `${name}_${values.count === 1 ? "one" : "other"}`
      : name;
  return (labels[plural] ?? labels[name] ?? name).replace(
    /\{\{(\w+)\}\}/g,
    (_, field) => String(values[field] ?? ""),
  );
};
export const poolText = { t, i18n: { resolvedLanguage: "en" } };
