// Writes web/src/chat/threadIcons.gen.ts from chat/thread-icons.mjs: one deep,
// per-icon Tabler import each, so the package still tree-shakes. Run after
// editing the list; it fails on a name Tabler doesn't ship.
import { existsSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { THREAD_ICONS, tablerName } from '../chat/thread-icons.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const icons = join(root, 'web/node_modules/@tabler/icons-react/dist/esm/icons')
const missing = THREAD_ICONS.filter((s) => !existsSync(join(icons, `${tablerName(s)}.mjs`)))
if (missing.length) { console.error(`Tabler has no icon for: ${missing.join(', ')}`); process.exit(1) }

const lines = [
  '// Generated by scripts/build-thread-icons.mjs from chat/thread-icons.mjs. Do not edit.',
  "import type { ComponentType } from 'react'",
  ...THREAD_ICONS.map((s, i) => `import I${i} from '@tabler/icons-react/dist/esm/icons/${tablerName(s)}.mjs'`),
  '',
  'export const THREAD_ICONS: Record<string, ComponentType<any>> = {',
  ...THREAD_ICONS.map((s, i) => `  '${s}': I${i},`),
  '}',
  '',
]
writeFileSync(join(root, 'web/src/chat/threadIcons.gen.ts'), lines.join('\n'))
console.log(`wrote ${THREAD_ICONS.length} thread icons`)
